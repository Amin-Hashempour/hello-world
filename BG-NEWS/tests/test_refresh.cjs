const fs = require('node:fs');
const assert = require('node:assert/strict');
const script = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8');
const start = script.indexOf('function mergeSource(');
const end = script.indexOf('async function refresh()', start);
const merge = new Function(script.slice(start, end) + '; return mergeSource;')();
const items = (...ids) => ids.map(id => ({ id, title: id, url: `https://example.org/${id}` }));
let state = { items: [], sources: {} };
for (const code of ['Z','V','G']) assert.equal(merge(state, code, items('3','2','1')), 1);
assert.equal(state.items.length, 3);
for (const code of ['Z','V','G']) assert.equal(merge(state, code, items('5','4','3','2','1')), 2);
assert.equal(state.items.length, 9);
const savedZ3 = state.items.find(item => item.source === 'Z' && item.id === '3');
savedZ3.image = 'https://old.invalid/image.jpg';
const refreshed = items('5','4','3','2','1');
refreshed.find(item => item.id === '3').image = '/api/image/' + 'a'.repeat(64);
assert.equal(merge(state, 'Z', refreshed), 0);
assert.equal(state.items.find(item => item.source === 'Z' && item.id === '3').image, '/api/image/' + 'a'.repeat(64));
assert.equal(merge(state, 'Z', items('5','4','3','2','1')), 0);
assert.equal(merge(state, 'Z', items('5','4','3','older')), 0);
state = JSON.parse(JSON.stringify(state));
assert.equal(merge(state, 'Z', items('6','5','4')), 1);
assert.equal(merge(state, 'G', []), 0);
let retry = {items: [], sources: {}};
assert.equal(merge(retry, 'V', []), 0);
assert.equal(merge(retry, 'V', items('3','2','1')), 1);
assert.equal(merge(state, 'G', items('9','8')), 2);
console.log('PASS: per-source first refresh, all new posts, duplicate prevention, older-post exclusion, persisted state, empty responses, delayed baseline, missing boundary');
